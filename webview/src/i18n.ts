const locale = document.documentElement.lang.toLowerCase();
const catalog = locale === "zh-cn" || locale.startsWith("zh-hans") ? ZH_CN : undefined;

export function t(message: string, args: Readonly<Record<string, string | number>> = {}): string {
    const localized = catalog?.[message] ?? message;
    return localized.replace(/\{([^{}]+)\}/gu, (placeholder, key: string) =>
        Object.prototype.hasOwnProperty.call(args, key) ? String(args[key]) : placeholder,
    );
}

